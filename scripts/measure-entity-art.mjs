import fs from 'node:fs/promises';
import sharp from 'sharp';

// Record visible bounds so transparent padding cannot determine display height.
export async function measureEntityArt() {
  const root = new URL('../public/assets/images/tex/', import.meta.url);
  const bounds = {};
  for (const file of (await fs.readdir(root)).sort()) {
    if (!/^(boss_|monster_|ambush_|npc(?:_|\.))/.test(file) || !file.endsWith('.png')) continue;
    const { data, info } = await sharp(await fs.readFile(new URL(file, root)))
      .ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    let top = info.height, bottom = 0;
    for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] < 100) continue;
      top = Math.min(top, y); bottom = Math.max(bottom, y + 1);
    }
    if (bottom <= top) throw new Error(`Empty entity texture: ${file}`);
    bounds[file.slice(0, -4)] = { top, bottom };
  }
  await fs.writeFile(new URL('../src/data/entityArtBounds.js', import.meta.url),
    '// Generated by scripts/measure-entity-art.mjs; refreshed by npm run art:build.\n' +
    `export const ENTITY_ART_BOUNDS = ${JSON.stringify(bounds, null, 2)};\n`);
}
